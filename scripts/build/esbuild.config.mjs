import esbuild from "esbuild";
import process from "process";
import { createRequire } from "module";
import wasmPlugin from "./wasm-plugin.mjs";
import nodeModuleShim from "./node-module-shim.mjs";
import svgrPlugin from "./svgr-plugin.mjs";
import { baseEsbuildOptions, runEsbuildContext } from "./esbuild-base.mjs";

// CommonJS plugin loaded via createRequire — pure JS, no ESM export needed.
const patchRendererUnsafeUnref = createRequire(import.meta.url)("./patch-renderer-unsafe-unref.js");
const { createBundleSizeGuard } = createRequire(import.meta.url)("./bundle-size-guard.js");

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/

// Polyfill for import.meta in CommonJS context
if (typeof import_meta === 'undefined') {
  var import_meta = {
    url: typeof __filename !== 'undefined' ? 'file://' + __filename : 'file:///obsidian-plugin'
  };
}

// Minimal \`process\` shim so the bundle survives MODULE EVALUATION on Obsidian
// mobile, whose WebView has no Node \`process\` global. Desktop-only code (Agent
// Mode) is statically imported and therefore evaluated on every platform; many
// of those modules — and bundled Node deps — read \`process.platform\`/\`.env\` at
// module scope, which throws "Can't find variable: process" on mobile and kills
// the whole plugin at load. On desktop (Electron) \`globalThis.process\` exists
// and is used as-is, so this only stubs mobile, where those code paths never run.
var process = globalThis.process || {
  env: {},
  platform: '',
  arch: '',
  argv: [],
  version: '',
  versions: {},
  cwd: function () { return '/'; },
  nextTick: function (cb) { Promise.resolve().then(cb); },
  on: function () {},
  off: function () {},
  once: function () {},
  emit: function () { return false; },
};
`;

const prod = process.argv[2] === "production";
const bundleSizeGuard = createBundleSizeGuard({ production: prod });

const context = await esbuild.context({
  ...baseEsbuildOptions(prod, {
    extraExternal: [
      "@codemirror/autocomplete",
      "@codemirror/collab",
      "@codemirror/commands",
      "@codemirror/language",
      "@codemirror/lint",
      "@codemirror/search",
      "@codemirror/state",
      "@codemirror/view",
      "@lezer/common",
      "@lezer/highlight",
      "@lezer/lr",
    ],
    extraDefine: {
      "import.meta.url": "import_meta.url",
    },
  }),
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  charset: "utf8",
  legalComments: "eof",
  outfile: "dist/main.js",
  plugins: [nodeModuleShim, svgrPlugin, wasmPlugin, patchRendererUnsafeUnref, bundleSizeGuard],
  minify: prod,
});

await runEsbuildContext(context, prod);
